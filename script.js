// Current language
let currentLang = localStorage.getItem('language') || 'fr';

// Set language function
function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('language', lang);

  // Update all elements with data-lang
  document.querySelectorAll('[data-lang]').forEach(element => {
    const key = element.getAttribute('data-lang');
    if (translations[lang][key]) {
      element.innerHTML = translations[lang][key];
    }
  });

  // Update language toggle button
  const toggleBtn = document.getElementById('lang-toggle');
  if (toggleBtn) {
    toggleBtn.textContent = translations[lang]['lang-toggle'];
  }

  // Update document lang attribute
  document.documentElement.lang = lang;

  // Update project modal if open
  const modal = document.getElementById('projectModal');
  if (modal && modal.getAttribute('aria-hidden') === 'false') {
    const body = document.getElementById('projectModalBody');
    const currentProjectId = body.getAttribute('data-project-id');
    if (currentProjectId && projects[currentProjectId]) {
      body.innerHTML = renderProjectContent(projects[currentProjectId], currentProjectId);
    }
  }
}

// Language toggle event
document.addEventListener('DOMContentLoaded', () => {
  const langToggle = document.getElementById('lang-toggle');
  if (langToggle) {
    langToggle.addEventListener('click', () => {
      const newLang = currentLang === 'fr' ? 'en' : 'fr';
      setLanguage(newLang);
      // Restart typewriter with new language
      restartTypewriter();
    });
  }
});

