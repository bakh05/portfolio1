// Contact form handler (mailto fallback)
function submitContact(e){
  e.preventDefault();
  const name = document.getElementById('name').value.trim();
  const email = document.getElementById('email').value.trim();
  const message = document.getElementById('message').value.trim();
  if(!name || !email || !message){
    alert(translations[currentLang]['form-fill-all']);
    return;
  }
  // open user's email client with prefilled message (simple fallback)
  const subject = encodeURIComponent(`Contact portfolio — ${name}`);
  const body = encodeURIComponent(`Nom: ${name}\nEmail: ${email}\n\n${message}`);
  window.location.href = `mailto:falloutambedou05@gmail.com?subject=${subject}&body=${body}`;
}

// Add asynchronous form submission for contact form with message display
document.addEventListener('DOMContentLoaded', () => {
  const contactForm = document.getElementById('contactForm');
  const formMessage = document.getElementById('formMessage');

  contactForm.addEventListener('submit', async (event) => {
    event.preventDefault();
    formMessage.textContent = '';
    formMessage.classList.remove('success', 'error');

    const formData = new FormData(contactForm);

    try {
      const response = await fetch(contactForm.action, {
        method: 'POST',
        body: formData
      });
      const result = await response.json();

      if(result.success) {
        formMessage.textContent = result.message || translations[currentLang]['form-success'];
        formMessage.classList.add('success');
        contactForm.reset();
      } else {
        formMessage.textContent = result.message || translations[currentLang]['form-error'];
        formMessage.classList.add('error');
      }
    } catch (error) {
      formMessage.textContent = translations[currentLang]['form-network-error'];
      formMessage.classList.add('error');
    }
  });
});
